#!/usr/bin/env bash
# Generates THROWAWAY local development secrets into .env.local at the repo root.
# Never use these values in production. Requires: node (>=20).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$ROOT/.env.local"
if [[ -f "$OUT" && "${1:-}" != "--force" ]]; then
  echo ".env.local already exists. Re-run with --force to overwrite." >&2
  exit 1
fi
node - "$ROOT/.env.example" "$OUT" <<'JS'
const fs = require('fs');
const crypto = require('crypto');
const [src, out] = process.argv.slice(2);
const rnd = (n) => crypto.randomBytes(n).toString('base64url');
const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
const pg = rnd(18), app = rnd(18);
const values = {
  POSTGRES_PASSWORD: pg,
  APP_DB_PASSWORD: app,
  DATABASE_URL: `postgresql://rsaas_app:${app}@localhost:5433/rsaas?schema=public`,
  MIGRATION_DATABASE_URL: `postgresql://rsaas_owner:${pg}@localhost:5433/rsaas?schema=public`,
  JWT_ACCESS_SECRET: rnd(48),
  JWT_REFRESH_SECRET: rnd(48),
  MFA_ENCRYPTION_KEY: crypto.randomBytes(32).toString('base64'),
  LICENSE_SIGNING_PRIVATE_KEY: privateKey.export({ format: 'der', type: 'pkcs8' }).toString('base64'),
  LICENSE_PUBLIC_KEY: publicKey.export({ format: 'der', type: 'spki' }).toString('base64'),
  BOOTSTRAP_SUPERADMIN_EMAIL: 'admin@example.com',
  BOOTSTRAP_SUPERADMIN_PASSWORD: 'Dev-' + rnd(12),
};
const lines = fs.readFileSync(src, 'utf8').split('\n').map((l) => {
  const m = l.match(/^([A-Z0-9_]+)=/);
  return m && values[m[1]] !== undefined ? `${m[1]}=${values[m[1]]}` : l;
});
fs.writeFileSync(out, '# GENERATED by gen-dev-secrets — throwaway dev values, never commit\n' + lines.join('\n'), { mode: 0o600 });
console.log(`Wrote ${out}`);
console.log(`Super Admin: ${values.BOOTSTRAP_SUPERADMIN_EMAIL} / ${values.BOOTSTRAP_SUPERADMIN_PASSWORD}`);
JS
